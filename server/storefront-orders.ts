interface PricedItem {
  product_id: string;
  variant_id: string | null;
  product_name: string;
  unit_name: string;
  conversion_factor: number;
  qty: number;
  unit_price: number;
  subtotal: number;
}

async function priceOneItem(client: Client, item: OrderItem): Promise<PricedItem> {
  const productRes = await client.execute({
    sql: 'SELECT id, name FROM products WHERE id = ? OR sku = ? LIMIT 1',
    args: [item.productId ?? '', item.sku ?? ''],
  });
  const product = productRes.rows[0] as unknown as { id: string; name: string } | undefined;
  if (!product) {
    throw new HttpError(404, 'product_not_found', 'Salah satu produk tidak lagi tersedia.');
  }

  if (item.variantId) {
    const variantRes = await client.execute({
      sql: "SELECT id FROM product_variants WHERE id = ? AND product_id = ? AND status = 'active' LIMIT 1",
      args: [item.variantId, product.id],
    });
    if (!variantRes.rows[0]) {
      throw new HttpError(404, 'variant_not_found', 'Pilihan varian produk sudah tidak tersedia.');
    }
  }

  const unitRes = await client.execute({
    sql: `SELECT price, conversion_factor
            FROM product_units
           WHERE product_id = ? AND name = ?
             AND ( (? IS NULL AND variant_id IS NULL) OR variant_id = ? )
           LIMIT 1`,
    args: [product.id, item.unitName, item.variantId, item.variantId],
  });
  const unit = unitRes.rows[0] as unknown as
    | { price: number; conversion_factor: number }
    | undefined;
  if (!unit) {
    throw new HttpError(404, 'unit_not_found', `Satuan "${item.unitName}" tidak tersedia untuk ${product.name}.`);
  }

  const unitPrice = Math.round(Number(unit.price));
  const subtotal = Math.round(item.qty * unitPrice);
  return {
    product_id: product.id,
    variant_id: item.variantId,
    product_name: product.name,
    unit_name: item.unitName,
    conversion_factor: Number(unit.conversion_factor),
    qty: item.qty,
    unit_price: unitPrice,
    subtotal,
  };
}

