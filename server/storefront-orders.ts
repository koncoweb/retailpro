export interface PublicOrderStatus {
  tenant: string;
  orderId: string;
  invoiceNumber: string;
  status: string;
  total: number;
  createdAt: string | null;
}

/**
 * Status of every split under a parent id, for the shopper's order page.
 *
 * When `slugs` is given (the create response told the client which sellers are
 * involved) only those databases are read; otherwise the read fans out over every
 * active tenant. The parent id is a UUID a stranger cannot enumerate, and only
 * status/total/invoice are returned — never the buyer's name or address.
 */
export async function readOrderStatuses(
  parent: string,
  slugs?: string[]
): Promise<PublicOrderStatus[]> {
  const tenants = slugs?.length
    ? await Promise.all(slugs.map((slug) => findActiveTenantBySlug(slug).catch(() => null)))
    : await listActiveTenants();

  const out: PublicOrderStatus[] = [];
  for (const tenant of tenants) {
    if (!tenant) continue;
    try {
      const rows = await withClient(tenant, async (client) => {
        const res = await client.execute({
          sql: `SELECT id, invoice_number, status, total, created_at
                  FROM storefront_orders WHERE parent_id = ?`,
          args: [parent],
        });
        return res.rows as unknown as {
          id: string;
          invoice_number: string;
          status: string;
          total: number;
          created_at: string | null;
        }[];
      });
      for (const row of rows) {
        out.push({
          tenant: tenant.slug,
          orderId: row.id,
          invoiceNumber: row.invoice_number,
          status: row.status,
          total: Number(row.total),
          createdAt: row.created_at,
        });
      }
    } catch (error) {
      console.error(
        `[storefront] status read for "${tenant.slug}" skipped:`,
        error instanceof Error ? error.message : error
      );
    }
  }
  return out;
}

