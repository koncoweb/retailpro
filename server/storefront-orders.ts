export interface RawOrderItem {
  tenant?: unknown;
  productId?: unknown;
  sku?: unknown;
  variantId?: unknown;
  unitName?: unknown;
  qty?: unknown;
}

export interface OrderItem {
  tenant: string;
  productId: string | null;
  sku: string | null;
  variantId: string | null;
  unitName: string;
  qty: number;
}

export interface TenantGroup {
  tenant: string;
  items: OrderItem[];
}

export interface GroupedOrder {
  parent: string;
  customer: { name: string; phone: string; address: string | null };
  fulfillment: 'pickup' | 'delivery';
  slot: string | null;
  notes: string | null;
  paymentChannel: string | null;
  paymentBankId: string | null;
  groups: TenantGroup[];
}

const MAX_ITEMS = 100;
const MAX_ITEMS_PER_SELLER = 50;

function str(value: unknown): string | null {
  if (typeof value !== 'string') return null;
  const trimmed = value.trim();
  return trimmed ? trimmed : null;
}

function positiveNumber(value: unknown): number | null {
  const n = typeof value === 'number' ? value : parseFloat(String(value));
  return Number.isFinite(n) && n > 0 ? n : null;
}

/**
 * Validate + normalize a raw create payload into one group per seller.
 *
 * Throws `HttpError(400)` with an Indonesian message on the first problem — a
 * stranger sees the same reason a cashier would. Pure: no database, no clock
 * (the parent id is generated by the caller), so it is unit-testable directly.
 */
export function groupOrderPayload(body: unknown): GroupedOrder {
  if (!body || typeof body !== 'object') {
    throw new HttpError(400, 'invalid_payload', 'Permintaan tidak valid.');
  }
  const raw = body as Record<string, unknown>;

  const rawItems = raw.items;
  if (!Array.isArray(rawItems) || rawItems.length === 0) {
    throw new HttpError(400, 'empty_cart', 'Keranjang belanja kosong.');
  }
  if (rawItems.length > MAX_ITEMS) {
    throw new HttpError(400, 'too_many_items', 'Terlalu banyak item dalam satu pesanan.');
  }

  const customerRaw = (raw.customer ?? {}) as Record<string, unknown>;
  const name = str(customerRaw.name);
  const phone = str(customerRaw.phone);
  const address = str(customerRaw.address);
  if (!name || name.length < 2) {
    throw new HttpError(400, 'missing_customer', 'Nama pemesan wajib diisi.');
  }
  if (!phone) {
    throw new HttpError(400, 'missing_phone', 'Nomor telepon pemesan wajib diisi.');
  }

  const fulfillment: 'pickup' | 'delivery' =
    str(raw.fulfillment) === 'delivery' ? 'delivery' : 'pickup';

  const groups = new Map<string, OrderItem[]>();
  for (const entry of rawItems as RawOrderItem[]) {
    if (!entry || typeof entry !== 'object') {
      throw new HttpError(400, 'invalid_item', 'Item pesanan tidak valid.');
    }
    const tenant = str(entry.tenant);
    if (!tenant) {
      throw new HttpError(400, 'missing_tenant', 'Setiap item harus menyebut toko penjualnya.');
    }
    const productId = str(entry.productId);
    const sku = str(entry.sku);
    if (!productId && !sku) {
      throw new HttpError(400, 'missing_product', 'Item pesanan tanpa produk.');
    }
    const unitName = str(entry.unitName);
    if (!unitName) {
      throw new HttpError(400, 'missing_unit', 'Item pesanan tanpa satuan.');
    }
    const qty = positiveNumber(entry.qty);
    if (!qty) {
      throw new HttpError(400, 'invalid_qty', 'Jumlah item pesanan tidak valid.');
    }
    const item: OrderItem = {
      tenant,
      productId,
      sku,
      variantId: str(entry.variantId),
      unitName,
      qty,
    };
    const list = groups.get(tenant) ?? [];
    list.push(item);
    groups.set(tenant, list);
  }

  for (const [tenant, items] of groups) {
    if (items.length > MAX_ITEMS_PER_SELLER) {
      throw new HttpError(400, 'too_many_items', `Terlalu banyak item untuk toko "${tenant}".`);
    }
  }

  return {
    parent: randomUUID(),
    customer: { name, phone, address },
    fulfillment,
    slot: str(raw.slot),
    notes: str(raw.notes),
    paymentChannel: str(raw.paymentChannel),
    paymentBankId: str(raw.paymentBankId),
    groups: [...groups.entries()].map(([tenant, items]) => ({ tenant, items })),
  };
}

