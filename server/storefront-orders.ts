/**
 * Storefront order engine: the marketplace cart becomes one `storefront_orders`
 * row PER SELLER, held in each seller's own tenant database.
 *
 * Why it lives in `server/` (not just inline in the handler): the money path has
 * to be trustworthy. Prices are recomputed here from `product_units`, never taken
 * from the browser; a `pending_payment` row touches neither stock nor reports, so
 * spamming the public create endpoint cannot distort a shop's numbers; and the
 * one place stock and revenue DO move — confirming payment — reuses the exact
 * checkout order the till follows (batch issue policy, per-batch deduction with a
 * `>=` guard, an audit row in the same transaction). The pure validator and the
 * fee/plan helpers are exported so the tests can drive them without a database.
 */
import { createClient, type Client, type Transaction } from '@libsql/client';
import { randomUUID } from 'node:crypto';
import { HttpError } from './http.js';
import { mintTenantToken } from './provision.js';
import { browserDbUrl } from './turso-platform.js';
import { parseJson } from '../src/lib/db/json.js';
