export interface CreatedSellerOrder {
  tenant: string;
  orderId: string;
  shopName: string;
  total: number;
  status: string;
  payment: {
    channel: string | null;
    banks: StorefrontBank[];
    qrisAvailable: boolean;
  };
}

export interface CreateOrdersResult {
  parentId: string;
  orders: CreatedSellerOrder[];
}

async function withClient<T>(
  tenant: ActiveTenant,
  fn: (client: Client) => Promise<T>
): Promise<T> {
  const { token } = await mintTenantToken(tenant.db_name, tenant.db_hostname);
  const client = createClient({ url: browserDbUrl(tenant.db_hostname), authToken: token });
  try {
    return await fn(client);
  } finally {
    client.close();
  }
}

/**
 * Interactive write transaction, committed on success and rolled back on any
 * throw. `@libsql/client` has no closure form, so commit/close/rollback is done
 * by hand here — the whole point of confirm/cancel being atomic.
 */
async function runWriteTx(
  client: Client,
  fn: (tx: Transaction) => Promise<void>
): Promise<void> {
  const tx = await client.transaction('write');
  try {
    await fn(tx);
    await tx.commit();
  } catch (error) {
    try {
      await tx.rollback();
    } catch {
      // already closed/rolled back
    }
    throw error;
  } finally {
    tx.close();
  }
}

/**
 * Persist one `storefront_orders` row per seller for a validated payload.
 *
 * Each seller resolves to its own tenant database; an unknown/inactive slug fails
 * the whole request (a half-placed marketplace order is worse than none). No
 * stock moves here — that is the confirm step's job.
 */
export async function createStorefrontOrders(body: unknown): Promise<CreateOrdersResult> {
  const order = groupOrderPayload(body);
  const orders: CreatedSellerOrder[] = [];

  for (const group of order.groups) {
    const tenant = await findActiveTenantBySlug(group.tenant);
    const config = await withClient(tenant, async (client) => {
      const priced: PricedItem[] = [];
      for (const item of group.items) {
        priced.push(await priceOneItem(client, item));
      }
      const subtotal = priced.reduce((sum, item) => sum + item.subtotal, 0);

      const orderId = randomUUID();
      const invoiceNumber = `SO/${Date.now()}/${orderId.slice(0, 8)}`;
      await client.execute({
        sql: `INSERT INTO storefront_orders
                (id, parent_id, invoice_number, shop_name, customer_name, customer_phone,
                 customer_address, fulfillment, slot, notes, payment_channel, payment_bank_id,
                 items, subtotal, shipping, total, status, created_at)
              VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 0, ?, 'pending_payment', ?)`,
        args: [
          orderId,
          order.parent,
          invoiceNumber,
          tenant.company_name,
          order.customer.name,
          order.customer.phone,
          order.customer.address,
          order.fulfillment,
          order.slot,
          order.notes,
          order.paymentChannel,
          order.paymentBankId,
          JSON.stringify(
            priced.map((p) => ({
              product_id: p.product_id,
              variant_id: p.variant_id,
              unit_name: p.unit_name,
              conversion_factor: p.conversion_factor,
              qty: p.qty,
              unit_price: p.unit_price,
            }))
          ),
          subtotal,
          subtotal,
          new Date().toISOString(),
        ],
      });

      const paymentConfig = await readPaymentConfig(client, tenant);
      return { subtotal, paymentConfig, orderId };
    });

    const transferChannel = config.paymentConfig.channels.find((c) => c.id === 'transfer');
    orders.push({
      tenant: group.tenant,
      orderId: config.orderId,
      shopName: tenant.company_name,
      total: config.subtotal,
      status: 'pending_payment',
      payment: {
        channel: order.paymentChannel,
        banks: transferChannel?.banks ?? config.paymentConfig.banks,
        qrisAvailable: config.paymentConfig.qrisAvailable,
      },
    });
  }

  return { parentId: order.parent, orders };
}

