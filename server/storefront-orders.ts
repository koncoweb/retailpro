interface OrderRow {
  id: string;
  parent_id: string;
  invoice_number: string;
  status: string;
  subtotal: number;
  payment_channel: string | null;
  items: string;
  transaction_id: string | null;
}

interface SnapshotItem {
  product_id: string;
  variant_id: string | null;
  unit_name: string;
  conversion_factor: number;
  qty: number;
  unit_price: number;
}

/** A batch row shaped for the issue-order comparator, plus the fields we bill. */
type BatchRow = IssueBatch & { id: string; quantity_current: number; cost_price: number };

function readIssueMethod(settings: Record<string, unknown>) {
  const inventory = settings[STOCK_ISSUE_SETTING_KEY];
  const field =
    inventory && typeof inventory === 'object'
      ? (inventory as Record<string, unknown>)[STOCK_ISSUE_METHOD_FIELD]
      : undefined;
  return normalizeStockIssueMethod(field);
}

async function loadOrder(client: Client, orderId: string): Promise<OrderRow> {
  const res = await client.execute({
    sql: `SELECT id, parent_id, invoice_number, status, subtotal, payment_channel, items, transaction_id
            FROM storefront_orders WHERE id = ?`,
    args: [orderId],
  });
  const row = res.rows[0] as unknown as OrderRow | undefined;
  if (!row) throw new HttpError(404, 'order_not_found', 'Pesanan tidak ditemukan.');
  return row;
}

async function resolveFulfilment(
  client: Client
): Promise<{ branchId: string; warehouseId: string }> {
  const branchRes = await client.execute(
    `SELECT id FROM branches
      WHERE status = 'active'
      ORDER BY (type = 'online') DESC, is_headquarters DESC, code ASC
      LIMIT 1`
  );
  const branchId = (branchRes.rows[0] as unknown as { id: string } | undefined)?.id;
  if (!branchId) {
    throw new HttpError(409, 'tenant_not_seeded', 'Cabang toko belum disiapkan, hubungi admin.');
  }
  const whRes = await client.execute({
    sql: `SELECT w.id FROM warehouses w
           WHERE w.status = 'active'
             AND (w.branch_id IS NULL OR w.branch_id <> ?)
           ORDER BY (w.branch_id IS NULL) DESC, (w.type = 'central') DESC,
                    w.is_default DESC, w.name ASC
           LIMIT 1`,
    args: [branchId],
  });
  const warehouseId = (whRes.rows[0] as unknown as { id: string } | undefined)?.id;
  if (!warehouseId) {
    throw new HttpError(409, 'tenant_not_seeded', 'Gudang toko belum disiapkan, hubungi admin.');
  }
  return { branchId, warehouseId };
}

export interface ConfirmResult {
  orderId: string;
  transactionId: string;
  invoiceNumber: string;
  total: number;
  feeAmount: number;
  status: string;
}

/**
 * Confirm that a shopper paid: write the tenant's `transactions` row and drain
 * gudang stock in ONE transaction, following the till's checkout order exactly.
 *
 * The marketplace shipping fee is deliberately NOT part of this — the tenant's
 * revenue is its own goods subtotal; platform delivery is settled elsewhere.
 * A stock shortfall aborts the whole transaction (nothing partial is written) and
 * answers with an Indonesian 409.
 */
export async function confirmStorefrontOrder(
  tenant: ActiveTenant,
  orderId: string,
  actor: { id: string }
): Promise<ConfirmResult> {
  return withClient(tenant, async (client) => {
    const order = await loadOrder(client, orderId);
    if (order.transaction_id) {
      throw new HttpError(409, 'already_confirmed', 'Pesanan ini sudah dikonfirmasi.');
    }
    if (order.status !== 'pending_payment') {
      throw new HttpError(409, 'bad_state', `Pesanan berstatus "${order.status}" tidak bisa dikonfirmasi.`);
    }
    const items = parseJson<SnapshotItem[]>(order.items, []);
    if (items.length === 0) {
      throw new HttpError(409, 'empty_order', 'Pesanan tidak memiliki item.');
    }

    const settingsRes = await client.execute('SELECT settings FROM tenants LIMIT 1');
    const settings = parseJson<Record<string, unknown>>(
      (settingsRes.rows[0] as unknown as { settings: string | null } | undefined)?.settings,
      {}
    );
    const issueMethod = readIssueMethod(settings);
    const channel: PaymentChannel | undefined = normalizeChannels(settings.payment_channels).find(
      (entry) => entry.id === order.payment_channel
    );
    const total = Number(order.subtotal);
    const feeAmount = channel ? computeMerchantFee(channel, total) : 0;
    const feeLabelValue = channel ? feeLabel(channel) : null;
    const paymentMethod = paymentMethodForChannel(order.payment_channel ?? 'cash');

    const { branchId, warehouseId } = await resolveFulfilment(client);

    // Pre-flight stock, before the write transaction opens.
    for (const item of items) {
      const required = item.qty * (item.conversion_factor || 1);
      const res = await client.execute({
        sql: `SELECT COALESCE(SUM(quantity_current), 0) AS available
                FROM product_batches
               WHERE product_id = ? AND warehouse_id = ? AND quantity_current > 0
                 AND (? IS NULL OR variant_id = ?)`,
        args: [item.product_id, warehouseId, item.variant_id, item.variant_id],
      });
      const available = Number((res.rows[0] as unknown as { available: number })?.available ?? 0);
      if (available + 0.001 < required) {
        throw new HttpError(409, 'insufficient_stock', `Stok tidak cukup untuk menyelesaikan pesanan (butuh ${required}, tersedia ${available}).`);
      }
    }

    let transactionId = '';
    await runWriteTx(client, async (tx) => {
      const insertRes = await tx.execute({
        sql: `INSERT INTO transactions
                (branch_id, cashier_id, invoice_number, total_amount, amount_paid,
                 payment_method, status, fee_amount, fee_label, source, created_at)
              VALUES (?, ?, ?, ?, ?, ?, 'completed', ?, ?, 'online', strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))
              RETURNING id`,
        args: [branchId, actor.id, order.invoice_number, total, total, paymentMethod, feeAmount, feeLabelValue],
      });
      transactionId = String((insertRes.rows[0] as unknown as { id: string }).id);

      for (const item of items) {
        const factor = item.conversion_factor || 1;
        let remaining = item.qty * factor;
        const batchesRes = await tx.execute({
          sql: `SELECT id, quantity_current, cost_price, received_at, expiry_date
                  FROM product_batches
                 WHERE product_id = ? AND warehouse_id = ? AND quantity_current > 0
                   AND (? IS NULL OR variant_id = ?)`,
          args: [item.product_id, warehouseId, item.variant_id, item.variant_id],
        });
        const batches = sortBatchesForIssue(
          batchesRes.rows as unknown as BatchRow[],
          issueMethod
        );
        for (const batch of batches) {
          if (remaining <= 0) break;
          const take = Math.min(remaining, Number(batch.quantity_current));
          const deduct = await tx.execute({
            sql: `UPDATE product_batches SET quantity_current = quantity_current - ?
                   WHERE id = ? AND quantity_current >= ?`,
            args: [take, batch.id, take],
          });
          if (deduct.rowsAffected === 0) {
            throw new HttpError(409, 'stock_changed', 'Stok berubah saat konfirmasi berjalan. Muat ulang lalu coba lagi.');
          }
          const soldQty = take / factor;
          await tx.execute({
            sql: `INSERT INTO transaction_items
                    (transaction_id, product_id, variant_id, batch_id, quantity,
                     unit_price, cost_price, subtotal, unit_name, conversion_factor)
                  VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
            args: [
              transactionId,
              item.product_id,
              item.variant_id,
              batch.id,
              soldQty,
              item.unit_price,
              Math.round(Number(batch.cost_price) * factor),
              Math.round(item.unit_price * soldQty),
              item.unit_name,
              factor,
            ],
          });
          remaining -= take;
        }
      }

      await tx.execute({
        sql: `UPDATE storefront_orders
                SET status = 'confirmed', confirmed_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now'),
                    confirmed_by = ?, transaction_id = ?
              WHERE id = ?`,
        args: [actor.id, transactionId, orderId],
      });

      await tx.execute({
        sql: `INSERT INTO audit_logs (action, entity, entity_id, details, user_id)
              VALUES ('checkout', 'transactions', ?, ?, ?)`,
        args: [
          transactionId,
          JSON.stringify({
            source: 'online',
            storefront_order_id: orderId,
            invoice_number: order.invoice_number,
            total_amount: total,
            fee_amount: feeAmount,
            payment_method: paymentMethod,
            item_count: items.length,
            stock_issue_method: issueMethod,
          }),
          actor.id,
        ],
      });
    });

    return {
      orderId,
      transactionId,
      invoiceNumber: order.invoice_number,
      total,
      feeAmount,
      status: 'confirmed',
    };
  });
}

export type OrderTransition = 'packing' | 'shipped' | 'done' | 'cancel';

const ALLOWED_TRANSITIONS = new Set<string>(['packing', 'shipped', 'done', 'cancel']);

/**
 * Move a confirmed order along (packing → shipped → done) or cancel it.
 *
 * Progression only touches the order row; a confirmed order that is cancelled has
 * its transaction voided and its stock returned, reusing the void discipline
 * (the bon is marked `void`, never deleted; each line restocks its own batch).
 */
export async function transitionStorefrontOrder(
  tenant: ActiveTenant,
  orderId: string,
  target: string,
  reason: string | null,
  actor: { id: string }
): Promise<{ status: string }> {
  if (!ALLOWED_TRANSITIONS.has(target)) {
    throw new HttpError(400, 'bad_transition', 'Status tujuan tidak dikenal.');
  }
  return withClient(tenant, async (client) => {
    const order = await loadOrder(client, orderId);

    if (target === 'cancel') {
      const trimmed = (reason ?? '').trim();
      if (trimmed.length < 3) {
        throw new HttpError(400, 'reason_required', 'Alasan pembatalan wajib diisi (minimal 3 karakter).');
      }
      if (order.status === 'cancelled' || order.status === 'void') {
        throw new HttpError(409, 'already_cancelled', 'Pesanan ini sudah dibatalkan.');
      }

      if (order.transaction_id) {
        await runWriteTx(client, async (tx) => {
          const itemsRes = await tx.execute({
            sql: 'SELECT id, batch_id, quantity, conversion_factor FROM transaction_items WHERE transaction_id = ? AND voided = 0',
            args: [order.transaction_id as string],
          });
          for (const line of itemsRes.rows as unknown as {
            id: string;
            batch_id: string | null;
            quantity: number;
            conversion_factor: number | null;
          }[]) {
            const base = Math.max(0, Number(line.quantity) * Number(line.conversion_factor ?? 1));
            if (line.batch_id && base > 0) {
              await tx.execute({
                sql: 'UPDATE product_batches SET quantity_current = quantity_current + ? WHERE id = ?',
                args: [base, line.batch_id],
              });
            }
            await tx.execute({
              sql: `UPDATE transaction_items
                      SET voided = 1, void_reason = ?, voided_by = ?,
                          voided_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now')
                    WHERE id = ? AND voided = 0`,
              args: [trimmed, actor.id, line.id],
            });
          }
          await tx.execute({
            sql: `UPDATE transactions
                    SET status = 'void', void_reason = ?, voided_by = ?,
                        voided_at = strftime('%Y-%m-%dT%H:%M:%fZ', 'now')
                  WHERE id = ?`,
            args: [trimmed, actor.id, order.transaction_id],
          });
          await tx.execute({
            sql: `UPDATE storefront_orders
                    SET status = 'cancelled', cancel_reason = ? WHERE id = ?`,
            args: [trimmed, orderId],
          });
          await tx.execute({
            sql: `INSERT INTO audit_logs (action, entity, entity_id, details, user_id)
                  VALUES ('void_transaction', 'storefront_orders', ?, ?, ?)`,
            args: [
              orderId,
              JSON.stringify({ reason: trimmed, transaction_id: order.transaction_id, restocked: true }),
              actor.id,
            ],
          });
        });
        return { status: 'cancelled' };
      }

      // Never confirmed: nothing to restock, just cancel the row.
      await client.execute({
        sql: `UPDATE storefront_orders SET status = 'cancelled', cancel_reason = ? WHERE id = ?`,
        args: [trimmed, orderId],
      });
      await client.execute({
        sql: `INSERT INTO audit_logs (action, entity, entity_id, details, user_id)
              VALUES ('void_transaction', 'storefront_orders', ?, ?, ?)`,
        args: [orderId, JSON.stringify({ reason: trimmed, transaction_id: null }), actor.id],
      });
      return { status: 'cancelled' };
    }

    // Progression (packing/shipped/done): only a confirmed order may advance.
    if (order.status !== 'confirmed') {
      throw new HttpError(409, 'bad_state', 'Hanya pesanan yang sudah dikonfirmasi pembayarannya dapat diproses lebih lanjut.');
    }
    await client.execute({
      sql: 'UPDATE storefront_orders SET status = ? WHERE id = ?',
      args: [target, orderId],
    });
    return { status: target };
  });
}
